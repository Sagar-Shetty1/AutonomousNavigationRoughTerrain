%% createScenarioIntegrationTestModel
% Build an isolated integration-test copy of the checkpoint model for the
% currently saved scenarioConfig.mat. The original checkpoint is untouched.
% This script prepares/updates the model only; it does NOT run a simulation.

clc;
projectRoot = pwd;
scenarioFile = fullfile(projectRoot, 'scenarioConfig.mat');
setupFile = fullfile(projectRoot, 'setupOffRoadProject.m');
sourceModelName = 'OffRoadMultibodyStage1_OnlineReplanCheckpoint';
sourceModelFile = fullfile(projectRoot, [sourceModelName '.slx']);
testModelName = 'OffRoadMultibodyStage1_ScenarioIntegrationTest';
testModelFile = fullfile(projectRoot, [testModelName '.slx']);

assert(isfile(scenarioFile), 'Missing %s. Save the scenario from the editor first.', scenarioFile);
assert(isfile(setupFile), 'Missing %s.', setupFile);
assert(isfile(sourceModelFile), 'Missing baseline model %s.', sourceModelFile);
assert(isfile(fullfile(projectRoot, 'onlineReplanFromPoseGeometryAware.m')), ...
    'Missing onlineReplanFromPoseGeometryAware.m.');
assert(~isfile(testModelFile), ...
    ['Test model file already exists: %s\nRename or remove that TEST file before rerunning. ', ...
     'The checkpoint model will not be overwritten.'], testModelFile);

if bdIsLoaded(testModelName)
    close_system(testModelName, 0);
end

fprintf('=== 1. Rebuilding terrain/planner workspace ===\n');
run(setupFile);

savedScenario = load(scenarioFile, 'scenarioConfig');
scenarioConfig = savedScenario.scenarioConfig;
assert(isstruct(scenarioConfig) && isfield(scenarioConfig, 'obstacles'), ...
    'scenarioConfig.mat does not contain a valid scenarioConfig struct.');

obs = scenarioConfig.obstacles(:);
[~, order] = sort([obs.id]);
obs = obs(order);
assert(numel(obs) == 3, ...
    'This first integration test expects exactly three configured obstacles.');
assert(all(arrayfun(@(o) strcmpi(o.shape, 'box'), obs)), ...
    'This integration test currently supports box obstacles only.');
assert(all(arrayfun(@(o) numel(o.centerXY) == 2 && numel(o.dimensions) == 3, obs)), ...
    'Each obstacle must have centerXY=[x y] and dimensions=[L W H].');

allCenters = vertcat(obs.centerXY);
obstacleXs = allCenters(:,1).';
obstacleYs = allCenters(:,2).';
obstacleSpawnTime = [obs.spawnTime];  % NaN = static; finite value = spawn time
obstacle3X = obstacleXs(3);           % legacy Constant block retained for compatibility
obstacle3Y = obstacleYs(3);

startPose = double(scenarioConfig.startPose(:).');
goalPose = double(scenarioConfig.goalPose(:).');
goalX = goalPose(1);
goalY = goalPose(2);
goalXY = goalPose(1:2);
obstacleClearance = double(scenarioConfig.planning.obstacleClearance);
maxWaypoints = double(scenarioConfig.planning.maxWaypoints);

staticMask = ~[obs.isDynamic];
staticObs = obs(staticMask);
assert(~isempty(staticObs), 'At least one static obstacle is required for the initial route.');
staticCenters = vertcat(staticObs.centerXY);
staticXs = staticCenters(:,1).';
staticYs = staticCenters(:,2).';

fprintf('\n=== 2. Calculating the initial route around static obstacles ===\n');
[originalPathPadded, initialWaypointCount, initialClearances, initialRouteLength] = ...
    onlineReplanFromPoseGeometryAware(startPose(1:2), goalXY, ...
    staticXs, staticYs, obstacleClearance, maxWaypoints);
originalPath = originalPathPadded(1:initialWaypointCount, :);
replannedPathPadded = originalPathPadded;
waypoints = originalPath;
newPath = originalPath;

% The current model has one physical brick, corresponding to obstacle 1.
% Parameterize that brick to match scenario obstacle 1 in this test copy.
obstacleLength = double(obs(1).dimensions(1));
obstacleWidth = double(obs(1).dimensions(2));
obstacleHeight = double(obs(1).dimensions(3));
underFirstObstacle = abs(X - obstacleXs(1)) <= obstacleLength/2 & ...
                     abs(Y - obstacleYs(1)) <= obstacleWidth/2;
assert(any(underFirstObstacle(:)), ...
    'Could not find terrain samples beneath the first obstacle footprint.');
maxTerrainZUnderObstacle = max(Z_multibody(underFirstObstacle));
obstacleCenterZ = maxTerrainZUnderObstacle + 0.005 + obstacleHeight/2;
zGround = obstacleCenterZ + 0.15;

fprintf('Initial route length: %.3f m; waypoints: %d\n', ...
    initialRouteLength, initialWaypointCount);
fprintf('Obstacles in saved scenario: %d\n', numel(obs));
for k = 1:numel(obs)
    if isnan(obs(k).spawnTime)
        spawnDescription = 'static from t=0';
    else
        spawnDescription = sprintf('spawns at t=%.3f s', obs(k).spawnTime);
    end
    fprintf('  %s: center=(%.3f, %.3f), size=(%.3f, %.3f, %.3f), %s\n', ...
        obs(k).name, obstacleXs(k), obstacleYs(k), ...
        obs(k).dimensions(1), obs(k).dimensions(2), obs(k).dimensions(3), ...
        spawnDescription);
end

fprintf('\n=== 3. Creating a separate test copy of the checkpoint model ===\n');
new_system(testModelName, 'FromFile', sourceModelFile);

try
    % Keep the existing top-level Constant block expressions, but supply
    % full three-obstacle arrays and per-obstacle activation times.
    expectedValues = {
        'ObstacleX',         'obstacleXs'
        'ObstacleY',         'obstacleYs'
        'Obstacle3X',        'obstacle3X'
        'Obstacle3Y',        'obstacle3Y'
        'ObstacleSpawnTime', 'obstacleSpawnTime'
        'PathWaypoints',     'originalPathPadded'
        'goalX',             'goalX'
        'goalY',             'goalY'
    };
    for k = 1:size(expectedValues,1)
        blockPath = [testModelName '/' expectedValues{k,1}];
        assert(getSimulinkBlockHandle(blockPath) ~= -1, ...
            'Required block missing from test copy: %s', blockPath);
        set_param(blockPath, 'Value', expectedValues{k,2});
    end

    brickPath = [testModelName '/PhysicalObstacle1'];
    assert(getSimulinkBlockHandle(brickPath) ~= -1, ...
        'PhysicalObstacle1 block is missing from the test copy.');
    set_param(brickPath, 'BrickDimensions', ...
        '[obstacleLength obstacleWidth obstacleHeight]');

    % Generalize the existing environment chart to use three positions and
    % a three-element spawn-time vector. NaN means present from t=0.
    environmentSource = sprintf([ ...
        'function [environmentXs, environmentYs] = ...\n' ...
        '    fcn(t, knownXs, knownYs, obstacle3X, obstacle3Y, spawnTime)\n' ...
        '%% Each position corresponds to one configured obstacle.\n' ...
        '%% NaN spawn time means static; finite time means hidden until that time.\n' ...
        'environmentXs = nan(1,3);\n' ...
        'environmentYs = nan(1,3);\n' ...
        'for k = 1:3\n' ...
        '    if numel(knownXs) >= k && numel(knownYs) >= k && numel(spawnTime) >= k\n' ...
        '        tk = spawnTime(k);\n' ...
        '        if isnan(tk) || t >= tk\n' ...
        '            environmentXs(k) = knownXs(k);\n' ...
        '            environmentYs(k) = knownYs(k);\n' ...
        '        end\n' ...
        '    end\n' ...
        'end\n' ...
        'end\n']);

    % Use the geometry-aware replanner inside the copy, preserving the
    % existing actual-position inputs and fixed-size 100x2 output.
    replanSource = sprintf([ ...
        'function [route, routeReady, replanEvent, replanStartX, replanStartY] = ...\n' ...
        '    fcn(x, y, newDetection, goalX, goalY, detectedX, detectedY)\n' ...
        'coder.extrinsic(''onlineReplanFromPoseGeometryAware'');\n' ...
        'persistent routeStored routeReadyState\n' ...
        'persistent knownXs knownYs knownCount waitCount pending\n' ...
        'persistent startXStored startYStored\n' ...
        'maxWaypoints = 100;\n' ...
        'maxObstacles = 3;\n' ...
        'settleSteps = 10; %% 0.2 s at 0.02 s sample time\n' ...
        'if isempty(routeReadyState)\n' ...
        '    routeStored = zeros(maxWaypoints,2);\n' ...
        '    routeReadyState = false;\n' ...
        '    knownXs = nan(1,maxObstacles);\n' ...
        '    knownYs = nan(1,maxObstacles);\n' ...
        '    knownCount = 0; waitCount = 0; pending = false;\n' ...
        '    startXStored = 0; startYStored = 0;\n' ...
        'end\n' ...
        'replanEvent = 0;\n' ...
        'if newDetection >= 0.5\n' ...
        '    duplicate = false;\n' ...
        '    for k = 1:knownCount\n' ...
        '        if hypot(knownXs(k)-detectedX, knownYs(k)-detectedY) < 0.25\n' ...
        '            duplicate = true; break;\n' ...
        '        end\n' ...
        '    end\n' ...
        '    if ~duplicate && knownCount < maxObstacles\n' ...
        '        knownCount = knownCount + 1;\n' ...
        '        knownXs(knownCount) = detectedX; knownYs(knownCount) = detectedY;\n' ...
        '        pending = true;\n' ...
        '    end\n' ...
        '    waitCount = 0;\n' ...
        'elseif pending\n' ...
        '    waitCount = waitCount + 1;\n' ...
        'end\n' ...
        'if pending && waitCount >= settleSteps\n' ...
        '    candidateRoute = zeros(maxWaypoints,2);\n' ...
        '    candidateRoute = onlineReplanFromPoseGeometryAware( ...\n' ...
        '        [x y], [goalX goalY], knownXs(1:knownCount), ...\n' ...
        '        knownYs(1:knownCount), 3.5, maxWaypoints);\n' ...
        '    routeStored = candidateRoute;\n' ...
        '    startXStored = routeStored(1,1); startYStored = routeStored(1,2);\n' ...
        '    routeReadyState = true; pending = false; waitCount = 0;\n' ...
        '    replanEvent = 1;\n' ...
        'end\n' ...
        'route = routeStored; routeReady = double(routeReadyState);\n' ...
        'replanStartX = startXStored; replanStartY = startYStored;\n' ...
        'end\n']);

    rt = sfroot;
    envChartPath = [testModelName '/DynamicObstacleEnvironment'];
    managerChartPath = [testModelName '/OnlineReplanManager'];
    envChart = find(rt, '-isa', 'Stateflow.EMChart', 'Path', envChartPath);
    managerChart = find(rt, '-isa', 'Stateflow.EMChart', 'Path', managerChartPath);
    assert(~isempty(envChart), 'Could not locate Stateflow MATLAB Function chart %s.', envChartPath);
    assert(~isempty(managerChart), 'Could not locate Stateflow MATLAB Function chart %s.', managerChartPath);
    envChart(1).Script = environmentSource;
    managerChart(1).Script = replanSource;

    fprintf('\n=== 4. Updating test copy (no simulation) ===\n');
    set_param(testModelName, 'SimulationCommand', 'update');

    save_system(testModelName, testModelFile);
    fprintf('\n=== SCENARIO INTEGRATION TEST MODEL READY ===\n');
    fprintf('Saved test copy: %s\n', testModelFile);
    fprintf('Original checkpoint preserved: %s.slx\n', sourceModelName);
    fprintf('Simulation has NOT been started.\n');
    fprintf(['Important: this version updates the planner/sensor environment and the first physical brick. ', ...
        'Obstacles 2 and 3 are still virtual sensor/planner obstacles, not separate Simscape collision bodies.\n']);
    fprintf('Initial route length %.3f m; initial waypoints %d.\n', ...
        initialRouteLength, initialWaypointCount);

catch ME
    if bdIsLoaded(testModelName)
        close_system(testModelName, 0);
    end
    rethrow(ME);
end
