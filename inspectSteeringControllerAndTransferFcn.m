function inspectSteeringControllerAndTransferFcn()
% INSPECTSTEERINGCONTROLLERANDTRANSFERFCN
% Read-only inspection of the steering command chain in the diagnostic copy.
% Does not modify block parameters, connections, simulation settings, or files.

model = 'OffRoadMultibodyStage1_PhysicalScenarioSpawnTest_Custom_UpperStopProbe_20261031_160339';
if ~bdIsLoaded(model)
    error('Diagnostic model is not loaded: %s', model);
end

fprintf('\n============================================================\n');
fprintf(' STEERING CONTROLLER + TRANSFER FUNCTION INSPECTION (READ ONLY)\n');
fprintf('============================================================\n');
fprintf('Model: %s\n', model);
fprintf('Dirty flag at start: %s\n', get_param(model, 'Dirty'));

% Inspect the first-order/second-order transfer function between the
% PurePursuitController steerCmd output and AckermannSteering delta input.
tfPath = [model '/Transfer Fcn'];
if getSimulinkBlockHandle(tfPath) ~= -1
    fprintf('\n------------------------------------------------------------\n');
    fprintf('BLOCK: Transfer Fcn\n');
    fprintf('------------------------------------------------------------\n');
    printParams(tfPath, {'BlockType','Numerator','Denominator','InitialStates', ...
        'SampleTime','AbsoluteTolerance','ParamDataTypeStr'});
    ph = get_param(tfPath, 'PortHandles');
    printInputSource(tfPath, ph.Inport(1), 'Transfer Fcn input');
    printOutputDestinations(tfPath, ph.Outport(1), 'Transfer Fcn output');
else
    fprintf('\nWARNING: %s not found.\n', tfPath);
end

% Inspect the steering command subsystem and Ackermann conversion subsystem.
inspectSubsystem([model '/PurePursuitController']);
inspectSubsystem([model '/AckermannSteering']);

% Inspect visible Stateflow chart objects associated with those subsystems.
% This can expose chart source/logic when the subsystem's internal S-Function
% is generated by Stateflow. No chart properties are changed.
fprintf('\n------------------------------------------------------------\n');
fprintf('STATEFLOW CHARTS ASSOCIATED WITH STEERING SUBSYSTEMS\n');
fprintf('------------------------------------------------------------\n');
try
    rt = sfroot;
    classes = {'Stateflow.Chart','Stateflow.EMChart','Stateflow.TruthTableChart', ...
               'Stateflow.StateTransitionTableChart'};
    foundAny = false;
    for ci = 1:numel(classes)
        try
            objs = rt.find('-isa', classes{ci});
        catch
            objs = [];
        end
        for k = 1:numel(objs)
            try, p = char(objs(k).Path); catch, p = ''; end
            try, n = char(objs(k).Name); catch, n = ''; end
            if contains(p, '/PurePursuitController') || contains(p, '/AckermannSteering')
                foundAny = true;
                fprintf('\nObject class: %s\nPath: %s\nName: %s\n', classes{ci}, p, n);
                printObjectProperty(objs(k), 'ActionLanguage');
                printObjectProperty(objs(k), 'UpdateMethod');
                printObjectProperty(objs(k), 'ChartUpdate');
                % MATLAB Function / Stateflow EMChart source
                if strcmp(classes{ci}, 'Stateflow.EMChart')
                    printObjectProperty(objs(k), 'Script');
                end
                % Classic Stateflow chart: report states, transitions, and data.
                if strcmp(classes{ci}, 'Stateflow.Chart')
                    try
                        states = objs(k).find('-isa', 'Stateflow.State');
                        fprintf('States: %d\n', numel(states));
                        for si = 1:numel(states)
                            try, lab = char(states(si).LabelString); catch, lab = ''; end
                            fprintf('  State %d: %s\n', si, oneLine(lab));
                        end
                    catch ME
                        fprintf('  State listing unavailable: %s\n', ME.message);
                    end
                    try
                        trans = objs(k).find('-isa', 'Stateflow.Transition');
                        fprintf('Transitions: %d\n', numel(trans));
                        for ti = 1:numel(trans)
                            try, lab = char(trans(ti).LabelString); catch, lab = ''; end
                            if ~isempty(strtrim(lab))
                                fprintf('  Transition %d: %s\n', ti, oneLine(lab));
                            end
                        end
                    catch ME
                        fprintf('  Transition listing unavailable: %s\n', ME.message);
                    end
                    try
                        dat = objs(k).find('-isa', 'Stateflow.Data');
                        fprintf('Data objects: %d\n', numel(dat));
                        for di = 1:numel(dat)
                            try, dn = char(dat(di).Name); catch, dn = ''; end
                            try, sc = char(dat(di).Scope); catch, sc = ''; end
                            try, dt = char(dat(di).Props.DataType.Method); catch, dt = ''; end
                            fprintf('  Data: %s | Scope=%s | DataType=%s\n', dn, sc, dt);
                        end
                    catch ME
                        fprintf('  Data listing unavailable: %s\n', ME.message);
                    end
                end
            end
        end
    end
    if ~foundAny
        fprintf('No Stateflow chart objects matched the two subsystem paths.\n');
    end
catch ME
    fprintf('Stateflow inspection unavailable: %s\n', ME.message);
end

fprintf('\n============================================================\n');
fprintf('INSPECTION COMPLETE — NO PARAMETERS OR CONNECTIONS CHANGED\n');
fprintf('Dirty flag at end: %s\n', get_param(model, 'Dirty'));
fprintf('============================================================\n\n');
end

function inspectSubsystem(path)
fprintf('\n------------------------------------------------------------\n');
fprintf('SUBSYSTEM: %s\n', path);
fprintf('------------------------------------------------------------\n');
if getSimulinkBlockHandle(path) == -1
    fprintf('Subsystem not found.\n');
    return;
end
printParams(path, {'BlockType','Mask','MaskType','LinkStatus','ReferenceBlock'});
try
    blocks = find_system(path, 'SearchDepth', 1, 'LookUnderMasks', 'all', ...
        'FollowLinks', 'off', 'Type', 'Block');
    fprintf('Direct/internal blocks found: %d\n', max(0, numel(blocks)-1));
    for i = 2:numel(blocks)
        b = blocks{i};
        try, bt = get_param(b, 'BlockType'); catch, bt = '?'; end
        try, mt = get_param(b, 'MaskType'); catch, mt = ''; end
        fprintf('  %s | BlockType=%s', b, bt);
        if ~isempty(mt), fprintf(' | MaskType=%s', mt); end
        if strcmp(bt, 'S-Function')
            safePrintParam(b, 'FunctionName');
            safePrintParam(b, 'Parameters');
            safePrintParam(b, 'Tag');
        elseif strcmp(bt, 'Inport') || strcmp(bt, 'Outport')
            safePrintParam(b, 'Port');
        end
        fprintf('\n');
    end
catch ME
    fprintf('Block listing failed: %s\n', ME.message);
end
end

function printParams(block, names)
for i = 1:numel(names)
    safePrintParam(block, names{i});
end
end

function safePrintParam(block, name)
try
    v = get_param(block, name);
    if isnumeric(v), v = mat2str(v); end
    if islogical(v), v = mat2str(v); end
    if iscell(v), v = strjoin(cellfun(@char, v, 'UniformOutput', false), ','); end
    if isstring(v), v = char(v); end
    if ischar(v)
        fprintf('  %-24s = %s\n', name, oneLine(v));
    else
        fprintf('  %-24s = %s\n', name, oneLine(evalc('disp(v)')));
    end
catch
    % Parameter is not supported by this block/version; omit it.
end
end

function printObjectProperty(obj, prop)
try
    v = obj.(prop);
    if ischar(v) || isstring(v)
        fprintf('%s: %s\n', prop, oneLine(char(v)));
    end
catch
end
end

function printInputSource(label, portHandle, heading)
fprintf('%s source:\n', heading);
try
    pc = get_param(portHandle, 'Line');
    if isempty(pc) || pc == -1
        fprintf('  Unconnected.\n');
        return;
    end
    src = get_param(pc, 'SrcPortHandle');
    srcBlock = get_param(src, 'Parent');
    srcPort = get_param(src, 'PortNumber');
    fprintf('  %s (output port %d)\n', srcBlock, srcPort);
catch ME
    fprintf('  Could not resolve source: %s\n', ME.message);
end
end

function printOutputDestinations(label, portHandle, heading)
fprintf('%s destinations:\n', heading);
try
    line = get_param(portHandle, 'Line');
    if isempty(line) || line == -1
        fprintf('  Unconnected.\n');
        return;
    end
    dst = get_param(line, 'DstPortHandle');
    for i = 1:numel(dst)
        if dst(i) ~= -1
            fprintf('  %s (input port %d)\n', get_param(dst(i), 'Parent'), get_param(dst(i), 'PortNumber'));
        end
    end
catch ME
    fprintf('  Could not resolve destinations: %s\n', ME.message);
end
end

function s = oneLine(s)
s = regexprep(char(s), '[\r\n]+', ' ');
s = strtrim(s);
end
