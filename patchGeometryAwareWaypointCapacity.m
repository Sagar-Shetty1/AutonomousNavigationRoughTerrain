function patchGeometryAwareWaypointCapacity()
% patchGeometryAwareWaypointCapacity
% Safely patches onlineReplanFromPoseGeometryAware.m so it removes only
% same-direction collinear intermediate points before checking its fixed
% waypoint capacity. This preserves the exact polyline geometry and keeps
% the output shape maxWaypoints-by-2 (currently 100-by-2), avoiding a Simulink
% signal-dimension change. Remaining segments are still validated by the
% planner's existing obstacle-envelope validation.
%
% Run from the project root or place this script in the project root.

projectRoot = fileparts(mfilename('fullpath'));
if isempty(projectRoot)
    projectRoot = pwd;
end
plannerFile = fullfile(projectRoot, 'onlineReplanFromPoseGeometryAware.m');
assert(isfile(plannerFile), ...
    'Could not find onlineReplanFromPoseGeometryAware.m in %s', projectRoot);

source = fileread(plannerFile);
if contains(source, 'compressCollinearPath(path)') && ...
        contains(source, 'function simplified = compressCollinearPath(path)')
    fprintf('Planner already has collinear waypoint compression; no changes made.\n');
    return;
end

% Match the existing waypoint-capacity assertion without assuming LF/CRLF.
pattern = ['(?s)([ \t]*waypointCount\s*=\s*size\(path,\s*1\);\s*' ...
    'assert\(waypointCount\s*<=\s*maxWaypoints,\s*\.\.\.\s*' ...
    '''Geometry-aware route has %d waypoints; output capacity is %d\.'',\s*\.\.\.\s*' ...
    'waypointCount\s*,\s*maxWaypoints\s*\);)'];
[startIdx, endIdx] = regexp(source, pattern, 'start', 'end');
assert(numel(startIdx) == 1, ...
    ['Could not identify the expected waypointCount/capacity assertion. ' ...
     'No changes were made. Inspect onlineReplanFromPoseGeometryAware.m manually.']);

replacement = sprintf([ ...
    'rawWaypointCount = size(path,1);\n' ...
    'path = compressCollinearPath(path);\n' ...
    'waypointCount = size(path,1);\n' ...
    'if waypointCount < rawWaypointCount\n' ...
    '    fprintf(''Collinear waypoint compression: %%d -> %%d waypoints; exact path geometry preserved.\\n'', ...\n' ...
    '        rawWaypointCount, waypointCount);\n' ...
    'end\n' ...
    'assert(waypointCount <= maxWaypoints, ...\n' ...
    '    ''Geometry-aware route still has %%d waypoints after collinear compression; output capacity is %%d.'', ...\n' ...
    '    waypointCount,maxWaypoints);']);

patchedSource = [source(1:startIdx-1), replacement, source(endIdx+1:end)];
helper = sprintf([ ...
    '\n\nfunction simplified = compressCollinearPath(path)\n' ...
    '%% Remove only intermediate points on the same straight, forward segment.\n' ...
    '%% This keeps the original piecewise-linear route exactly unchanged.\n' ...
    'if size(path,1) <= 2\n' ...
    '    simplified = path;\n' ...
    '    return;\n' ...
    'end\n' ...
    'simplified = path(1,:);\n' ...
    'for i = 2:size(path,1)\n' ...
    '    simplified(end+1,:) = path(i,:); %#ok<AGROW>\n' ...
    '    while size(simplified,1) >= 3\n' ...
    '        a = simplified(end-2,:);\n' ...
    '        b = simplified(end-1,:);\n' ...
    '        c = simplified(end,:);\n' ...
    '        v1 = b-a;\n' ...
    '        v2 = c-b;\n' ...
    '        cross2 = v1(1)*v2(2) - v1(2)*v2(1);\n' ...
    '        scale = max(norm(v1)*norm(v2), 1);\n' ...
    '        sameLine = abs(cross2) <= 1e-10*scale;\n' ...
    '        sameDirection = dot(v1,v2) > 0;\n' ...
    '        if sameLine && sameDirection\n' ...
    '            simplified(end-1,:) = [];\n' ...
    '        else\n' ...
    '            break;\n' ...
    '        end\n' ...
    '    end\n' ...
    'end\n' ...
    'end\n']);
patchedSource = [patchedSource helper];

stamp = datestr(now, 'yyyymmdd_HHMMSS');
backupFile = fullfile(projectRoot, ...
    ['onlineReplanFromPoseGeometryAware_preWaypointCompression_' stamp '.m']);
assert(copyfile(plannerFile, backupFile), 'Could not create planner backup.');
fprintf('Planner backup created: %s\n', backupFile);

tempFile = [plannerFile '.tmp'];
fid = fopen(tempFile, 'w');
assert(fid >= 0, 'Could not open temporary planner file for writing.');
try
    count = fwrite(fid, patchedSource, 'char');
    fclose(fid);
catch ME
    fclose(fid);
    if isfile(tempFile), delete(tempFile); end
    rethrow(ME);
end
assert(count == numel(patchedSource), 'Could not write the complete patched planner source.');
[ok,msg] = movefile(tempFile, plannerFile, 'f');
assert(ok, 'Could not replace planner source: %s', msg);

clear onlineReplanFromPoseGeometryAware
rehash;
verifySource = fileread(plannerFile);
assert(contains(verifySource, 'compressCollinearPath(path)') && ...
       contains(verifySource, 'function simplified = compressCollinearPath(path)'), ...
       'Post-write verification failed. Restore from backup: %s', backupFile);

fprintf('\n=== WAYPOINT CAPACITY PATCH APPLIED ===\n');
fprintf('Planner: %s\n', plannerFile);
fprintf('Only same-direction collinear intermediate points are removed.\n');
fprintf('The output matrix remains maxWaypoints-by-2; no Simulink signal width is increased.\n');
fprintf('The existing route-envelope validation runs on the simplified route.\n');
fprintf('No model was loaded, updated, or saved. No simulation was started.\n');
end
