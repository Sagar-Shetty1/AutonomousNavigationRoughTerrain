function scenarioConfig = defaultRoverScenario()
% defaultRoverScenario
% Single source of truth for the current three-obstacle baseline scenario.
% Units: metres, seconds, radians. Shapes are specified in XY with Z height.
%
% Axis-aligned box obstacles are supported by the geometry-aware 2-D planner
% and MATLAB viewer. The Simscape model currently has only one physical brick;
% additional physical obstacle geometries are a separate integration task.

scenarioConfig.schemaVersion = 1;
scenarioConfig.name = 'Three-obstacle online-replanning baseline';
scenarioConfig.startPose = [2.0, 2.0, pi/4]; % [x y yaw]
scenarioConfig.goalPose  = [14.0, 12.0, 0.0];
scenarioConfig.planning.obstacleClearance = 3.5; % Legacy fallback for unknown/non-box obstacles
scenarioConfig.planning.geometryMargin = 0.10; % Additional XY margin beyond rover footprint
scenarioConfig.planning.maxWaypoints = 100;
scenarioConfig.simulation.stopTime = 45.0;

obstacleTemplate = struct( ...
    'id', 0, ...
    'name', '', ...
    'shape', 'box', ...
    'centerXY', [0 0], ...
    'dimensions', [1.0 1.0 0.5], ... % [length width height]
    'isDynamic', false, ...
    'spawnTime', NaN);

obstacles = repmat(obstacleTemplate, 3, 1);

obstacles(1) = struct( ...
    'id', 1, 'name', 'Obstacle 1', 'shape', 'box', ...
    'centerXY', [9.0 6.5], 'dimensions', [1.0 1.0 0.5], ...
    'isDynamic', false, 'spawnTime', NaN);

obstacles(2) = struct( ...
    'id', 2, 'name', 'Obstacle 2', 'shape', 'box', ...
    'centerXY', [11.5 8.0], 'dimensions', [1.0 1.0 0.5], ...
    'isDynamic', false, 'spawnTime', NaN);

obstacles(3) = struct( ...
    'id', 3, 'name', 'Dynamic obstacle', 'shape', 'box', ...
    'centerXY', [13.5 5.0], 'dimensions', [1.0 1.0 0.5], ...
    'isDynamic', true, 'spawnTime', 8.0);

scenarioConfig.obstacles = obstacles;
end
